-- Esquema de demonstração para explorar metadados PostgreSQL.
CREATE TABLE organizations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, slug TEXT NOT NULL UNIQUE, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
 name TEXT NOT NULL, email TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE (organization_id, email)
);
CREATE TABLE roles (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE user_roles (
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
 assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY (user_id, role_id)
);
CREATE TABLE projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
 owner_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
 name TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'active'
 CHECK (status IN ('active','paused','completed')),
 settings JSONB NOT NULL DEFAULT '{}'::jsonb, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 assigned_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
 title TEXT NOT NULL, description TEXT, priority SMALLINT NOT NULL DEFAULT 3 CHECK (priority BETWEEN 1 AND 5),
 due_date DATE, completed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE task_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 author_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
 body TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE tags (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE task_tags (
 task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE, PRIMARY KEY (task_id, tag_id)
);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT REFERENCES organizations(id) ON DELETE SET NULL,
 actor_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
 event_type TEXT NOT NULL, payload JSONB NOT NULL DEFAULT '{}'::jsonb,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_app_users_org ON app_users(organization_id);
CREATE INDEX idx_projects_org_status ON projects(organization_id, status);
CREATE INDEX idx_tasks_project_due ON tasks(project_id, due_date);
CREATE INDEX idx_comments_task_created ON task_comments(task_id, created_at);
CREATE INDEX idx_audit_org_time ON audit_events(organization_id, occurred_at DESC);
CREATE INDEX idx_audit_payload ON audit_events USING GIN(payload);

